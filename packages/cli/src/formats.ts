import { escapeMarkdownTableCell } from './markdown.js';
import type { LocalResult } from './local-scan';
import { findingFingerprint } from '../../core/src/baseline';

export function outputJson(result: LocalResult): string {
  return JSON.stringify(result, null, 2);
}

function escapeHtml(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

