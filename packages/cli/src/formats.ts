export function outputSarif(result: LocalResult): string {
  const accepted = new Map(result.suppressedFindings.map(s => [findingFingerprint(s.finding), s.reason]));
  const runs = [{
    tool: { driver: { name: 'AI Skill Shield', informationUri: 'https://github.com/skill-shield', rules: [] } },
    results: result.findings.map(f => ({
      ruleId: f.title,
      suppressions: accepted.has(findingFingerprint(f)) ? [{ kind: 'external', status: 'accepted', justification: accepted.get(findingFingerprint(f)) }] : undefined,
      level: f.severity === 'critical' || f.severity === 'high' ? 'error' : f.severity === 'medium' ? 'warning' : 'note',
      message: { text: `${f.title}: ${f.message}` },
      locations: [{
        physicalLocation: {
          artifactLocation: { uri: (f.filePath || 'SKILL.md').split('/').map(encodeURIComponent).join('/') },
          region: { startLine: f.lineNumber || 1 },
        },
      }],
    })),
    properties: { score: result.score, riskLevel: result.riskLevel, verdict: result.verdict, coverage: result.coverage, dependencyAdvisories: result.dependencyAdvisories, suppressedFindings: result.suppressedFindings },
  }];
  return JSON.stringify({ $schema: 'https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json', version: '2.1.0', runs }, null, 2);
}

export function outputMarkdown(result: LocalResult): string {
  let md = `# AI Skill Shield Scan Report\n\n`;
  md += `**Score:** ${result.score}/100\n`;
  md += `**Verdict:** ${result.verdict}\n`;
  md += `**Highest Finding Severity:** ${result.riskLevel.toUpperCase()}\n`;
  md += `**Findings:** ${result.findings.length}\n**Coverage:** ${result.coverage.status} (${result.coverage.inspectedFiles} inspected, ${result.coverage.skippedFiles.length} exclusions)\n**Accepted findings:** ${result.suppressedFindings.length}\n\n`;
  if (result.findings.length === 0) {
    md += `No issues found.\n`;
  } else {
    md += `| Severity | Category | Title | File |\n| --- | --- | --- | --- |\n`;
    for (const f of result.findings) {
      md += `| ${f.severity.toUpperCase()} | ${escapeMarkdownTableCell(f.category)} | ${escapeMarkdownTableCell(f.title)} | ${escapeMarkdownTableCell(f.filePath || 'SKILL.md')}:${f.lineNumber || 1} |\n`;
    }
  }
  if (result.coverage.skippedFiles.length) md += '\n## Coverage exclusions\n\n' + result.coverage.skippedFiles.map(f => `- ${escapeMarkdownTableCell(f.path)}: ${escapeMarkdownTableCell(f.reason)}`).join('\n') + '\n';
  if (result.suppressedFindings.length) md += '\n## Accepted findings\n\n' + result.suppressedFindings.map(s => `- ${escapeMarkdownTableCell(s.finding.title)}: ${escapeMarkdownTableCell(s.reason)}`).join('\n') + '\n';
  if (result.dependencyAdvisories) md += `\n**Dependency advisories:** ${result.dependencyAdvisories.status} (${result.dependencyAdvisories.checkedPackages} exact packages checked)\n`;
  return md;
}
